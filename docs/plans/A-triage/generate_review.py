#!/usr/bin/env python3
"""Generate/refresh REVIEW.md — the per-commit decision table for A.2.

Reads commits.json (A.1 output). Writes REVIEW.md with one row per commit,
oldest first. Preserves the Check / Decision / Comment columns of existing
rows (keyed by short SHA), so the table can be regenerated safely after
origin/master advances or after re-running triage_commits.py.

Rows whose A.1 risk is SKIP are pre-decided as Skip.
The Commit cell links to commits/<short_sha>.md when that file exists.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
COMMITS_JSON = os.path.join(HERE, "commits.json")
REVIEW_MD = os.path.join(HERE, "REVIEW.md")
ANALYSIS_DIR = os.path.join(HERE, "commits")

HEADER = """# A.2 — Commit Review Table

Decision record for every commit in `4.17.0.0..origin/master`.
Generated by `generate_review.py` from `commits.json`; the **Check /
Decision / Comment columns are hand-maintained** and survive regeneration.

## Process (one commit at a time, top to bottom)

1. Take the first row with an empty Check column.
2. Read the full diff: `git show <sha>`. **Never decide from the subject
   line or the Risk column — both are heuristics and both have already
   been caught lying** (a commit titled "New option" that flips default
   behaviour; merge commits that looked empty). Only the actual diff
   decides.
3. Write `commits/<short_sha>.md` explaining every **Fix**, **Update**,
   **Add** and **Remove** in the commit.
4. Decide whether any backward-compatible fix applies to the restored
   4.17.x tree; record Decision + Comment here and mark Check `x`.
5. Applying the fix itself is a separate, gated step (sub-project D —
   needs tests green and per-commit user approval).

Pre-seeded `Skip` rows (risk SKIP) come from A.1 **file lists**, not
commit messages, and were each re-verified against `git show --numstat`
on 2026-08-22. Merge commits use the combined merge diff — three merges
that carried real changes were reclassified that day.

All 371 diffs are exported to `diffs/<short_sha>.txt` by `export_diffs.py`
(git-ignored, regenerable) so the whole history is searchable at once:
`rg -il "collection was modified" docs/plans/A-triage/diffs/`.

## Decision vocabulary

| Decision | Meaning |
| --- | --- |
| `Apply` | Contains a backward-compatible fix worth porting to 4.17.x |
| `Partial` | Only part of the commit qualifies (analysis file says which) |
| `Skip` | No applicable fix (feature, rewrite-only, docs, version bump) |
| `Postpone` | Possibly applicable, but decision needs the test harness or more context |

## Commits (oldest first — processing order)

| Check | Date | Commit | Risk | Subject | Decision | Comment |
| --- | --- | --- | --- | --- | --- | --- |
"""


def load_existing():
    """Return {short_sha: (check, decision, comment)} from current REVIEW.md."""
    if not os.path.exists(REVIEW_MD):
        return {}
    kept = {}
    row_re = re.compile(r"^\|([^|]*)\|[^|]*\|\s*(?:\[)?([0-9a-f]{8})", re.I)
    for line in open(REVIEW_MD, encoding="utf-8"):
        m = row_re.match(line.strip())
        if not m:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 7:
            kept[m.group(2)] = (cells[0], cells[5], cells[6])
    return kept


def esc(text):
    return text.replace("|", "\\|")


def main():
    doc = json.load(open(COMMITS_JSON, encoding="utf-8"))
    rows = sorted(doc["commits"], key=lambda c: (c["date"], c["sha"]))
    existing = load_existing()
    out = [HEADER]
    for c in rows:
        short = c["short_sha"]
        check, decision, comment = existing.get(short, ("", "", ""))
        if not decision and c["risk_level"] == "SKIP":
            check, decision, comment = "x", "Skip", c["risk_reason"]
        cell = (f"[{short}](commits/{short}.md)"
                if os.path.exists(os.path.join(ANALYSIS_DIR, short + ".md"))
                else short)
        out.append("| {} | {} | {} | {} | {} | {} | {} |\n".format(
            check, c["date"], cell, c["risk_level"],
            esc(c["subject"]), decision, esc(comment) if comment else ""))
    done = sum(1 for line in out if line.startswith("| x "))
    out[0] = out[0].replace(
        "## Commits (oldest first — processing order)",
        f"**Progress:** {done} / {len(rows)} processed.\n\n"
        "## Commits (oldest first — processing order)")
    with open(REVIEW_MD, "w", encoding="utf-8", newline="\n") as f:
        f.writelines(out)
    print(f"Wrote REVIEW.md: {len(rows)} rows, {done} processed")


if __name__ == "__main__":
    main()
